#!/usr/bin/env python3
"""Recompile the game's 68000 code to C++: build/m68k/.

  <set>_NN.cpp   the functions of each code set (main, then each overlay)
  m68k_funcs.h   their declarations
  m68k_tables.cpp  address -> function tables per set, and the code maps
                 (bytes compiled as instructions) for the self-modifying
                 code check
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from m68k.analyze import analyze, load_config   # noqa: E402
from m68k.codegen import generate                # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/m68k"
PER_FILE = 120


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def main() -> int:
    config = load_config(ROOT / "config/xenon2.json")
    hunks = json.loads((ROOT / "build/hunks.json").read_text())
    relocs = [a for h in hunks["hunks"] for a in h.get("reloc_at", [])]
    image = bytearray((ROOT / "build/image.bin").read_bytes())
    sets = analyze(image, ROOT / "game/data", config, relocs)
    names = {cs.name: ("m" if i == 0 else f"o{i}") for i, cs in enumerate(sets)}
    OUT.mkdir(parents=True, exist_ok=True)

    header = ["// Generated by tools/recompile.py.", "#pragma once", '#include "runtime/m68k.h"', ""]
    sources, changed = [], 0
    for cs in sets:
        prefix = names[cs.name]
        for entry in sorted(cs.functions):
            header.append(f"void {prefix}_{entry:06x}(u32 at);")
        chunks = generate(cs, sets, names, config["overlay_range"])
        for n in range(0, len(chunks), PER_FILE):
            path = OUT / f"{prefix}_{n // PER_FILE:02d}.cpp"
            text = "// Generated by tools/recompile.py.\n#include \"m68k_funcs.h\"\n\n" + "\n".join(chunks[n:n + PER_FILE])
            changed += write_if_changed(path, text)
            sources.append(path.name)
    write_if_changed(OUT / "m68k_funcs.h", "\n".join(header) + "\n")

    # Tables: every entry (at 0) and every resume address of every function.
    t = ["// Generated by tools/recompile.py.", '#include "m68k_funcs.h"', '#include "runtime/dispatch.h"', ""]
    for i, cs in enumerate(sets):
        prefix = names[cs.name]
        rows = {}
        for entry in sorted(cs.functions):
            rows[entry] = (f"{prefix}_{entry:06x}", 0)
        for entry in sorted(cs.functions):
            for r in sorted(cs.functions[entry].resumes):
                if r in cs.functions[entry].insns:
                    rows.setdefault(r, (f"{prefix}_{entry:06x}", r))
        t.append(f"static const DispatchEntry table_{prefix}[] = {{")
        t += [f"    {{0x{a:06x}, {fn}, 0x{at:06x}}}," for a, (fn, at) in sorted(rows.items())]
        t.append("};")
        # The code map of the set's own bytes (overlays: their slot only).
        covered = sorted(b for b in cs.covered if cs.owns(b))
        lo = min(covered) & ~7 if covered else 0
        hi = (max(covered) | 7) + 1 if covered else 0
        bits = bytearray((hi - lo) // 8)
        for b in covered:
            bits[(b - lo) >> 3] |= 1 << (b & 7)
        t.append(f"static const u8 map_{prefix}[] = {{" + ",".join(str(x) for x in bits) + "};")
        t.append("")
    t.append("const CodeSet kCodeSets[] = {")
    for cs in sets:
        prefix = names[cs.name]
        covered = sorted(b for b in cs.covered if cs.owns(b))
        lo = min(covered) & ~7 if covered else 0
        t.append(f'    {{"{cs.name}", table_{prefix}, sizeof(table_{prefix}) / sizeof(DispatchEntry), '
                 f'map_{prefix}, 0x{lo:06x}, sizeof(map_{prefix})}},')
    t.append("};")
    t.append(f"const int kCodeSetCount = {len(sets)};")
    lo, hi = config["overlay_range"]
    t.append(f"const u32 kOverlayStart = 0x{lo:06x}, kOverlayEnd = 0x{hi:06x};")
    write_if_changed(OUT / "m68k_tables.cpp", "\n".join(t) + "\n")
    (OUT / "sources.json").write_text(json.dumps(sources + ["m68k_tables.cpp"]) + "\n")
    funcs = sum(len(cs.functions) for cs in sets)
    print(f"recompile: {funcs} functions in {len(sources)} files ({changed} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
